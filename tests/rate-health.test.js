const assert = require('node:assert/strict');
const { assess } = require('../tools/check-rate-health.js');
const { freshness } = require('../js/rate-freshness.js');
const now = Date.parse('2026-10-27T03:00:00Z');
const meta = { fetchedAt: '2026-10-26' };
const pages = { loan: 'data-rates-fetched="2026-10-26"', savings: 'data-rates-fetched="2026-10-26"' };
const run = { status: 'completed', conclusion: 'success', created_at: '2026-10-26T01:53:43Z' };
assert.deepEqual(assess(meta, pages, run, now), []);
assert.ok(assess(meta, {}, run, now).length);
assert.ok(assess(meta, null, run, now).length);
assert.ok(assess(meta, pages, {...run,created_at:'2026-10-28T00:00:00Z'}, now).length);
for (const conclusion of ['failure', 'cancelled', 'timed_out']) assert.ok(assess(meta, pages, {...run, conclusion}, now).length);
assert.ok(assess(meta, pages, null, now).length);
assert.ok(assess(meta, {...pages, loan: 'data-rates-fetched="2026-10-19"'}, run, now).length);
assert.ok(assess({fetchedAt:'2026-10-01'}, pages, run, now).length);
assert.ok(assess(meta, pages, {...run,status:'in_progress'}, now).length);
assert.equal(freshness('2026-10-19', now), 'snapshot');
assert.equal(freshness('2026-10-18', now), 'delayed');
assert.equal(freshness('2026-10-26', Date.parse('2026-10-25T16:00:00Z')), 'snapshot');
console.log('rate health: success, failure, missing, mismatch, stale, stuck, KST and delay boundaries passed');
