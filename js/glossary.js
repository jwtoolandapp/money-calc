  function escapeHtml(text) {
    return String(text == null ? '' : text)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  // 브라우저와 빌드타임 사전 렌더러(tools/prerender-glossary.mjs)가 함께 쓰는
  // 단일 마크업 생성기. 양쪽 결과가 항상 같아야 하므로 여기만 고치면 된다.
  function buildGlossaryHtml(terms) {
    var listHtml = terms.map(function (t, i) {
      var exampleHtml = t.example
        ? '<div class="example easy-mode">' + escapeHtml(t.example) + '</div>'
        : '';
      return (
        '<details class="glossary-item"' + (i === 0 ? ' open' : '') + '>' +
          '<summary>' + escapeHtml(t.term) + '</summary>' +
          '<div class="glossary-body">' +
            '<p class="normal-mode">' + escapeHtml(t.normal) + '</p>' +
            '<p class="easy-mode">' + escapeHtml(t.easy) + '</p>' +
            exampleHtml +
          '</div>' +
        '</details>'
      );
    }).join('');

    return (
      '<div class="glossary-head">' +
        '<h2 id="glossary-heading">🔤 쉬운 용어 설명</h2>' +
        '<label class="glossary-toggle">' +
          '<span>더 쉽게 설명</span>' +
          '<input type="checkbox" id="glossary-easy-toggle">' +
          '<span class="switch" aria-hidden="true"></span>' +
        '</label>' +
      '</div>' +
      '<div class="glossary-list">' + listHtml + '</div>'
    );
  }

  function bindEasyToggle(section) {
    var toggle = section.querySelector('#glossary-easy-toggle');
    if (!toggle) return;
    toggle.addEventListener('change', function () {
      document.body.classList.toggle('easy-glossary', this.checked);
    });
  }

  function renderGlossary(pageKey, mountId) {
    // 사전 렌더링된 정적 마크업이 이미 있으면 다시 그리지 않고 토글만 연결한다.
    // (크롤러가 읽는 것은 이 정적 마크업이다.)
    var existing = document.querySelector('.glossary-section');
    if (existing) {
      bindEasyToggle(existing);
      return;
    }

    var terms = TERMS[pageKey];
    if (!terms || !terms.length) return;
    var mount = document.getElementById(mountId || 'glossary-mount');
    if (!mount) return;

    var section = document.createElement('section');
    section.className = 'glossary-section';
    section.setAttribute('aria-labelledby', 'glossary-heading');
    section.innerHTML = buildGlossaryHtml(terms);

    mount.replaceWith(section);
    bindEasyToggle(section);
  }

  global.MoneyCalcGlossary = {
    render: renderGlossary,
    buildHtml: buildGlossaryHtml,
    TERMS: TERMS
  };
